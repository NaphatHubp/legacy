package legacyknight.core;

/**
 * "หน้าจอ" ที่เกมอยู่ตอนนี้ (เกมจะอยู่ได้แค่หน้าเดียวในแต่ละช่วงเวลา)
 */
public enum GameState {
    /** หน้าเมนูหลัก */
    MENU,
    /** หน้าสอนวิธีเล่น */
    TUTORIAL,
    /** หน้าแผนที่เลือกด่าน */
    MAP,
    /** หน้าเนื้อเรื่อง (ฉากเปิดเรื่อง / ก่อนเข้าด่าน / ฉากจบ) */
    STORY,
    /** กำลังเล่นด่าน */
    PLAY,
    /** เล่นชนะ */
    WIN,
    /** เล่นแพ้ */
    LOSE
}
